#[derive(Clone, Copy)]
pub(crate) struct ThemePalette {
    pub(crate) name: &'static str,
    pub(crate) description: &'static str,
    pub(crate) window: Color32,
    pub(crate) panel: Color32,
    pub(crate) faint: Color32,
    pub(crate) extreme: Color32,
    pub(crate) code: Color32,
    pub(crate) inactive: Color32,
    pub(crate) hovered: Color32,
    pub(crate) accent: Color32,
    pub(crate) accent_hover: Color32,
    pub(crate) text: Color32,
    pub(crate) muted: Color32,
    pub(crate) stroke: Color32,
    pub(crate) dim_alpha: u8,
}

pub(crate) fn resolve_palette(theme: ThemeId, custom: ThemePalette) -> ThemePalette {
    match theme {
        ThemeId::Custom => {
            let mut p = custom;
            p.name = "Custom";
            p.description = "Editable colors — tune accent and surfaces below";
            p
        }
        other => other.palette(),
    }
}
